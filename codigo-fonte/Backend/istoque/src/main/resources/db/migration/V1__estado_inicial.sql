-- Tipos enumerados ------------------------------------------------------------

CREATE TYPE tipo_movimentacao AS ENUM ('entrada', 'saida');

CREATE TYPE motivo_movimentacao AS ENUM (
    'compra', 'reposicao', 'venda', 'consumo', 'producao',
    'perda', 'descarte', 'ajuste', 'outro'
);

CREATE TYPE motivo_perda AS ENUM (
    'vencimento', 'deterioracao', 'armazenamento_inadequado', 'acidente', 'outro'
);

-- Tabelas ---------------------------------------------------------------------

CREATE TABLE empresa (
    id                   integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME empresas_id_seq),
    razao_social         varchar(255) NOT NULL,
    nome_fantasia        varchar(255),
    cnpj                 varchar(255) NOT NULL,
    email                varchar(255),
    telefone             varchar(255),
    dias_alerta_validade integer DEFAULT 7,
    ativo                boolean NOT NULL DEFAULT true,
    criado_em            timestamp(0) with time zone NOT NULL DEFAULT now(),
    atualizado_em        timestamp(0) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT empresas_pkey PRIMARY KEY (id),
    CONSTRAINT empresas_cnpj_key UNIQUE (cnpj)
);

CREATE TABLE unidade_medida (
    id    integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME unidades_medida_id_seq),
    sigla varchar(10) NOT NULL,
    nome  varchar(40) NOT NULL,
    CONSTRAINT unidades_medida_pkey PRIMARY KEY (id),
    CONSTRAINT unidades_medida_sigla_key UNIQUE (sigla)
);

CREATE TABLE perfil (
    id         integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME perfis_id_seq),
    empresa_id integer NOT NULL,
    nome       varchar(255) NOT NULL,
    descricao  varchar(255),
    criado_em  timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT perfis_pkey PRIMARY KEY (id),
    CONSTRAINT uk_perfil_empresa_nome UNIQUE (empresa_id, nome)
);

CREATE TABLE perfil_permissao (
    perfil_id integer NOT NULL,
    permissao varchar(255) NOT NULL,
    CONSTRAINT perfil_permissao_permissao_check CHECK (permissao IN (
        'USUARIO_GERENCIAR', 'PRODUTO_GERENCIAR', 'ESTOQUE_MOVIMENTAR', 'ESTOQUE_AJUSTAR',
        'PERDA_REGISTRAR', 'RECEITA_GERENCIAR', 'PRODUCAO_REGISTRAR', 'RELATORIO_VISUALIZAR'
    ))
);

CREATE TABLE usuario (
    id                integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME usuarios_id_seq),
    empresa_id        integer NOT NULL,
    perfil_id         integer NOT NULL,
    nome              varchar(255) NOT NULL,
    email             varchar(255) NOT NULL,
    senha_hash        varchar(255) NOT NULL,
    ativo             boolean NOT NULL DEFAULT true,
    ultimo_acesso     timestamp with time zone,
    criado_em         timestamp with time zone NOT NULL DEFAULT now(),
    atualizado_em     timestamp with time zone NOT NULL DEFAULT now(),
    bloqueado_ate     timestamp(6) with time zone,
    tentativas_falhas integer NOT NULL,
    CONSTRAINT usuarios_pkey PRIMARY KEY (id),
    CONSTRAINT usuarios_email_key UNIQUE (email)
);

CREATE TABLE categoria (
    id         integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME categorias_id_seq),
    empresa_id integer NOT NULL,
    nome       varchar(80) NOT NULL,
    descricao  varchar(255),
    CONSTRAINT categorias_pkey PRIMARY KEY (id)
);

CREATE TABLE produto (
    id                integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME produtos_id_seq),
    empresa_id        integer NOT NULL,
    categoria_id      integer,
    unidade_medida_id integer NOT NULL,
    codigo            varchar(50),
    nome              varchar(120) NOT NULL,
    descricao         varchar(255),
    tipo              varchar(255) NOT NULL DEFAULT 'insumo',
    quantidade_atual  numeric(12,3) NOT NULL DEFAULT 0,
    estoque_minimo    numeric(12,3) NOT NULL DEFAULT 0,
    estoque_maximo    numeric(12,3),
    controla_validade boolean NOT NULL DEFAULT false,
    ativo             boolean NOT NULL DEFAULT true,
    criado_em         timestamp with time zone NOT NULL DEFAULT now(),
    atualizado_em     timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT produtos_pkey PRIMARY KEY (id),
    CONSTRAINT produto_tipo_check CHECK (tipo IN ('insumo', 'revenda', 'ambos')),
    CONSTRAINT ck_produto_qtd_nao_negativa CHECK (quantidade_atual >= 0),
    CONSTRAINT ck_produto_minimo CHECK (estoque_minimo >= 0),
    CONSTRAINT ck_produto_maximo CHECK (estoque_maximo IS NULL OR estoque_maximo >= estoque_minimo)
);

CREATE TABLE lote (
    id               integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME lotes_id_seq),
    empresa_id       integer NOT NULL,
    produto_id       integer NOT NULL,
    codigo           varchar(50),
    data_validade    date NOT NULL,
    quantidade_atual numeric(12,3) NOT NULL DEFAULT 0,
    criado_em        timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT lotes_pkey PRIMARY KEY (id),
    CONSTRAINT ck_lote_qtd_nao_negativa CHECK (quantidade_atual >= 0)
);

CREATE TABLE receita (
    id            integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME receitas_id_seq),
    empresa_id    integer NOT NULL,
    nome          varchar(120) NOT NULL,
    descricao     text,
    ativo         boolean NOT NULL DEFAULT true,
    criado_em     timestamp with time zone NOT NULL DEFAULT now(),
    atualizado_em timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT receitas_pkey PRIMARY KEY (id)
);

CREATE TABLE receita_item (
    receita_id integer NOT NULL,
    produto_id integer NOT NULL,
    quantidade numeric(12,3) NOT NULL,
    CONSTRAINT receita_itens_pkey PRIMARY KEY (receita_id, produto_id),
    CONSTRAINT ck_item_quantidade_positiva CHECK (quantidade > 0)
);

CREATE TABLE producao (
    id                   integer GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME producoes_id_seq),
    empresa_id           integer NOT NULL,
    receita_id           integer NOT NULL,
    usuario_id           integer NOT NULL,
    quantidade_produzida integer NOT NULL,
    observacao           text,
    criado_em            timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT producoes_pkey PRIMARY KEY (id),
    CONSTRAINT ck_producao_quantidade_positiva CHECK (quantidade_produzida > 0)
);

CREATE TABLE movimentacao (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME movimentacoes_id_seq),
    empresa_id           integer NOT NULL,
    produto_id           integer NOT NULL,
    lote_id              integer,
    usuario_id           integer NOT NULL,
    producao_id          integer,
    tipo                 tipo_movimentacao NOT NULL,
    motivo               motivo_movimentacao NOT NULL,
    motivo_perda         motivo_perda,
    quantidade           numeric(12,3) NOT NULL,
    quantidade_anterior  numeric(12,3) NOT NULL,
    quantidade_posterior numeric(12,3) NOT NULL,
    justificativa        text,
    criado_em            timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT movimentacoes_pkey PRIMARY KEY (id),
    CONSTRAINT ck_mov_quantidade_positiva CHECK (quantidade > 0),
    -- motivos de entrada so com tipo entrada, e de saida so com tipo saida
    CONSTRAINT ck_mov_motivo_entrada CHECK (motivo NOT IN ('compra', 'reposicao') OR tipo = 'entrada'),
    CONSTRAINT ck_mov_motivo_saida CHECK (
        motivo NOT IN ('venda', 'consumo', 'producao', 'perda', 'descarte') OR tipo = 'saida'
    ),
    -- motivo_perda preenchido se e somente se o motivo for perda ou descarte
    CONSTRAINT ck_mov_motivo_perda CHECK ((motivo IN ('perda', 'descarte')) = (motivo_perda IS NOT NULL)),
    -- producao_id preenchido se e somente se o motivo for producao
    CONSTRAINT ck_mov_producao CHECK ((motivo = 'producao') = (producao_id IS NOT NULL)),
    CONSTRAINT ck_mov_ajuste_justificativa CHECK (
        motivo <> 'ajuste' OR length(trim(coalesce(justificativa, ''))) > 0
    )
);

-- Chaves estrangeiras ---------------------------------------------------------

ALTER TABLE perfil
    ADD CONSTRAINT perfis_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE;

ALTER TABLE perfil_permissao
    ADD CONSTRAINT perfil_permissoes_perfil_id_fkey FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE CASCADE DEFERRABLE;

ALTER TABLE usuario
    ADD CONSTRAINT usuarios_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE,
    ADD CONSTRAINT usuarios_perfil_id_fkey FOREIGN KEY (perfil_id) REFERENCES perfil (id) DEFERRABLE;

ALTER TABLE categoria
    ADD CONSTRAINT categorias_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE;

ALTER TABLE produto
    ADD CONSTRAINT produtos_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE,
    ADD CONSTRAINT produtos_categoria_id_fkey FOREIGN KEY (categoria_id) REFERENCES categoria (id) DEFERRABLE,
    ADD CONSTRAINT produtos_unidade_medida_id_fkey FOREIGN KEY (unidade_medida_id) REFERENCES unidade_medida (id) DEFERRABLE;

ALTER TABLE lote
    ADD CONSTRAINT lotes_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE,
    ADD CONSTRAINT lotes_produto_id_fkey FOREIGN KEY (produto_id) REFERENCES produto (id) DEFERRABLE;

ALTER TABLE receita
    ADD CONSTRAINT receitas_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE;

ALTER TABLE receita_item
    ADD CONSTRAINT receita_itens_receita_id_fkey FOREIGN KEY (receita_id) REFERENCES receita (id) ON DELETE CASCADE DEFERRABLE,
    ADD CONSTRAINT receita_itens_produto_id_fkey FOREIGN KEY (produto_id) REFERENCES produto (id) DEFERRABLE;

ALTER TABLE producao
    ADD CONSTRAINT producoes_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE,
    ADD CONSTRAINT producoes_receita_id_fkey FOREIGN KEY (receita_id) REFERENCES receita (id) DEFERRABLE,
    ADD CONSTRAINT producoes_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id) DEFERRABLE;

ALTER TABLE movimentacao
    ADD CONSTRAINT movimentacoes_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) DEFERRABLE,
    ADD CONSTRAINT movimentacoes_produto_id_fkey FOREIGN KEY (produto_id) REFERENCES produto (id) DEFERRABLE,
    ADD CONSTRAINT movimentacoes_lote_id_fkey FOREIGN KEY (lote_id) REFERENCES lote (id) DEFERRABLE,
    ADD CONSTRAINT movimentacoes_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id) DEFERRABLE,
    ADD CONSTRAINT movimentacoes_producao_id_fkey FOREIGN KEY (producao_id) REFERENCES producao (id) DEFERRABLE;

