-- Os bancos que ja existiam foram marcados como estando nesta versao (baseline)
-- e nao rodam este script. Ele so roda em banco vazio.
-- Os nomes das restricoes e das sequencias seguem os do banco, que ainda tem
-- nomes no plural do modelo anterior. As mudancas no modelo vem nas proximas versoes.
