-- V11: telefone da empresa confirmado por SMS (HU021).

ALTER TABLE empresa ADD COLUMN telefone_verificado_em timestamp(0) with time zone;

CREATE TABLE codigo_verificacao (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    empresa_id  integer NOT NULL,
    finalidade  varchar(40) NOT NULL,
    codigo_hash varchar(100) NOT NULL,
    expira_em   timestamp(0) with time zone NOT NULL,
    tentativas  integer NOT NULL DEFAULT 0,
    usado       boolean NOT NULL DEFAULT false,
    enviado_em  timestamp(0) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT codigo_verificacao_pkey PRIMARY KEY (id),
    CONSTRAINT codigo_verificacao_empresa_id_fkey FOREIGN KEY (empresa_id) REFERENCES empresa (id) ON DELETE CASCADE,
    CONSTRAINT codigo_verificacao_finalidade_check CHECK (finalidade IN ('CONFIRMACAO_TELEFONE'))
);

CREATE INDEX codigo_verificacao_empresa_finalidade_enviado_idx
    ON codigo_verificacao (empresa_id, finalidade, enviado_em);

UPDATE empresa SET telefone = NULL WHERE trim(telefone) = '';

UPDATE empresa SET telefone = '+' || regexp_replace(telefone, '[ ()+.-]', '', 'g')
WHERE regexp_replace(telefone, '[ ()+.-]', '', 'g') ~ '^55[1-9][0-9]{9,10}$';

UPDATE empresa SET telefone = '+55' || regexp_replace(telefone, '[ ().-]', '', 'g')
WHERE regexp_replace(telefone, '[ ().-]', '', 'g') ~ '^[1-9][0-9]{9,10}$';
